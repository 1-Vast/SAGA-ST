#!/bin/bash
set -e
set -o pipefail

echo "=================================================================="
echo "🚀 151510 全透明破局网格 (实时显示进度 + 防内存假死)"
echo "策略: 降低过采样率防假死，缩小感受野保护 Layer 4"
echo "=================================================================="

# 1. 确定性环境与底层线程控制
unset OMP_NUM_THREADS
export OMP_NUM_THREADS=2
export MKL_NUM_THREADS=2
export OPENBLAS_NUM_THREADS=2
export NUMEXPR_NUM_THREADS=2
export NUMBA_THREADING_LAYER=workqueue
export CUBLAS_WORKSPACE_CONFIG=:4096:8
export CUDA_VISIBLE_DEVICES=0

H5_PATH="/root/autodl-tmp/DLPFC/151510_dropNaN.h5ad"
H5_RAW="/root/autodl-tmp/DLPFC/151510.h5ad"
OUT_DIR="/root/autodl-tmp/DLPFC/151510_transparent"
mkdir -p "$OUT_DIR/cluster_results"

SUMMARY_LOG="$OUT_DIR/transparent_summary.tsv"
echo -e "K_KNN\tLAMBDA\tHARD_R\tALPHA\tW_SPA\tRES\tARI\tNMI" > "$SUMMARY_LOG"

# ==========================================
# 训练搜索空间 (2 x 2 x 2 x 2 = 16 组核心训练)
# ==========================================
K_KNN_LIST=(10 12)             # 锁定小感受野，不让周围的细胞吞噬极薄的Layer 4
LAMBDA_LIST=(0.3 0.4)          # 降低重建束缚
HARD_R_LIST=(0.75 0.85)        # 强推斥力，撕开粘连
ALPHA_LIST=(0.40 0.50)         # 空间权重

# 聚类验证空间 (每组特征测 4 次)
W_SPA_LIST=(0.35 0.40)         # 摒弃大刷子，用细排笔
RES_LIST=(0.65 0.66)

TOTAL_TRAINS=$(( ${#K_KNN_LIST[@]} * ${#LAMBDA_LIST[@]} * ${#HARD_R_LIST[@]} * ${#ALPHA_LIST[@]} ))
current=1

for k_knn in "${K_KNN_LIST[@]}"; do
for lam in "${LAMBDA_LIST[@]}"; do
for hard_r in "${HARD_R_LIST[@]}"; do
for alp in "${ALPHA_LIST[@]}"; do

  PREFIX="$OUT_DIR/train_${current}"
  
  echo "=================================================================="
  echo ">>> 正在执行 [Train $current/$TOTAL_TRAINS]"
  echo ">>> 参数: K=$k_knn, Lam=$lam, Hard=$hard_r, Alpha=$alp"
  echo "=================================================================="

  # 1. 核心特征提取 
  # ⚠️ 注意：这里没有 > /dev/null，终端会直接实时打印 tqdm 进度条！
  # ⚠️ 注意：--neg_oversample 改为了 5，大幅降低 CPU 内存压力！
  python -m model.main \
    --h5 "$H5_PATH" \
    --out_prefix "$PREFIX" \
    --use_scanpy_workflow --pca_comps 50 \
    --graph_model KNN --k "$k_knn" \
    --dim 64 --K 2 --hidden 512 --embed_agg concat \
    --alpha "$alp" --topN 60 \
    --lambda_recon "$lam" --mask_ratio_feat 0.4 \
    --epochs 500 --pos_per_epoch 15000 \
    --layer_aware --no_layer_fallback \
    --pseudo_layer_bins 12 \
    --neg_layer_margin 1 --layer_gamma 6.0 \
    --normal_aware --normal_knn 30 --normal_margin 1.0 --normal_gamma 2.0 \
    --neg_hard_ratio "$hard_r" --neg_oversample 5 \
    --activation prelu --scheduler \
    --lr 0.001 --weight_decay 0.02 --seed 42 --device cuda

  # 检查是否生成了特征文件，如果因为意外中断则跳过聚类
  NPZ_FILE=$(ls "${PREFIX}"*.npz 2>/dev/null | head -n 1)
  if [ -z "$NPZ_FILE" ]; then 
      echo "    [!] 找不到特征文件，可能训练异常中断，跳过本组聚类。"
      ((current++))
      continue 
  fi

  echo ">>> 训练完成！正在执行下游 4 组精细聚类测试..."

  # 2. 聚类验证 (聚类非常快，所以这里依然屏蔽输出，只打印最终得分)
  for w_spa in "${W_SPA_LIST[@]}"; do
      w_emb=$(awk -v w="$w_spa" 'BEGIN {print 1.0 - w}')
      for res in "${RES_LIST[@]}"; do
          
          CLU_PREFIX="${PREFIX}_wspa${w_spa}_res${res}"
          
          python -m model.cluster \
            --npz "$NPZ_FILE" --h5 "$H5_RAW" \
            --label_key "sce.layer_guess" \
            --method robust --n_clusters 7 \
            --knn_k 20 --resolution "$res" \
            --robust_res_list "0.64,0.65,0.66,0.67" \
            --robust_seeds 7 --robust_smooth_iter 1 \
            --w_spa "$w_spa" --w_emb "$w_emb" \
            --power 1 --power_alpha 0.5 \
            --refine_k 15 --refine_iter 1 \
            --use_rep emb --calc_acc \
            --out_prefix "$CLU_PREFIX" > /dev/null 2>&1 || true

          MET_FILE="$OUT_DIR/cluster_results/$(basename ${CLU_PREFIX}).robust.metrics.txt"
          if [ -f "$MET_FILE" ]; then
              ari=$(awk '$1=="ARI" {print $2}' "$MET_FILE")
              nmi=$(awk '$1=="NMI" {print $2}' "$MET_FILE")
              
              echo -e "${k_knn}\t${lam}\t${hard_r}\t${alp}\t${w_spa}\t${res}\t${ari}\t${nmi}" >> "$SUMMARY_LOG"
              
              is_high=$(awk -v a="$ari" 'BEGIN {print (a >= 0.58) ? 1 : 0}')
              if [ "$is_high" -eq 1 ]; then
                  printf "    🔥 ARI=\033[31m%s\033[0m, NMI=%s (w_spa=%s, res=%s)\n" "$ari" "$nmi" "$w_spa" "$res"
              else
                  printf "    ARI=%s, NMI=%s (w_spa=%s, res=%s)\n" "$ari" "$nmi" "$w_spa" "$res"
              fi
          fi
      done
  done
  
  # 3. 及时清理 H5AD 节约磁盘，只保留战利品 NPZ
  rm -f "${PREFIX}"*.h5ad
  ((current++))

done
done
done
done

echo "=================================================================="
echo "🎯 全透明突击完成！终极排行榜 Top 10:"
echo "=================================================================="
printf "%-6s %-8s %-8s %-6s %-6s %-6s %-10s %-10s\n" "K_KNN" "LAMBDA" "HARD_R" "ALPHA" "W_SPA" "RES" "ARI" "NMI"
echo "------------------------------------------------------------------"
sort -t$'\t' -k7 -n -r "$SUMMARY_LOG" | head -n 10 | awk -F'\t' '{printf "%-6s %-8s %-8s %-6s %-6s %-6s \033[32m%-10s\033[0m %-10s\n", $1, $2, $3, $4, $5, $6, $7, $8}'
echo "=================================================================="


